#!/usr/bin/env python3
"""Generate data/credits.toml (the in-game Credits panel) from ASSETS.toml.

ASSETS.toml is the source of truth for third-party assets but is not exported with the
game; data/*.toml is. Run after editing ASSETS.toml; `--check` fails when stale.
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LICENSE_NAMES = {"CC0-1.0": "CC0 1.0", "CC-BY-3.0": "CC BY 3.0", "CC-BY-4.0": "CC BY 4.0"}
# Exact attribution strings the licensors / art lead asked for (CC-BY needs one).
ATTRIBUTION = {
    "crazy_joe": '"Animated Wizard" by Quaternius, CC BY 3.0',
    "elders": '"Animated Wizard" by Quaternius (Elders, recoloured), CC BY 3.0 - https://poly.pizza/m/kttbFvCl2C',
}


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    assets = tomllib.loads((ROOT / "ASSETS.toml").read_text())["asset"]
    out = ["# GENERATED by tools/gen_credits.py from ASSETS.toml - do not edit.\n"]
    for a in assets:
        lic = LICENSE_NAMES.get(a["license"], a["license"])
        key = a["path"].rstrip("/").rsplit("/", 1)[-1]
        author = a["author"].split(" (")[0]
        line = ATTRIBUTION.get(key, "%s by %s, %s" % (a["name"], author, lic))
        out.append(
            "\n[[credit]]\nname = %s\nauthor = %s\nlicense = %s\nsource = %s\nline = %s\n"
            % (q(a["name"]), q(author), q(lic), q(a["source"]), q(line))
        )
    return "".join(out)


def main() -> int:
    p = ROOT / "data" / "credits.toml"
    text = render()
    if "--check" in sys.argv:
        if not p.exists() or p.read_text() != text:
            print("data/credits.toml is stale: run tools/gen_credits.py")
            return 1
        print("credits: OK")
        return 0
    p.write_text(text)
    print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
