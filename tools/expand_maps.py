#!/usr/bin/env python3
"""Closed levels. The Association keeps its interior wings. The other levels keep
their greybox and dress props and do not grow an open-zone terrain block.
  tools/expand_maps.py            rewrite the blocks
  tools/expand_maps.py --check    exit 1 if a TOML is out of date
"""
from __future__ import annotations

import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# ---- EXPAND_BEGIN (generated by tools/expand_maps.py; edit that, not this) ----\n"
END = "# ---- EXPAND_END ----\n"
DRESS = "# ---- DRESS_BEGIN"
N = "assets/kenney/nature-kit/"
Q = "assets/quaternius/enemies/props/"
ROCK = [0.42, 0.4, 0.38]
DIRT = [0.33, 0.27, 0.2]


def v(p) -> str:
    return "[" + ", ".join(str(round(float(x), 3)) for x in p) + "]"


class Map:
    def __init__(self, terrain: dict | None):
        self.out = [] if terrain is None else ["[terrain]\n" + "".join(f"{k} = {v(x) if isinstance(x, (list, tuple)) and not isinstance(x[0], str) else _val(x)}\n"
                                             for k, x in terrain.items())]
        self.rects: list[tuple[float, float, float, float]] = []

    def box(self, name, kind, center, size, color, rot=None, hidden=False):
        s = f'[[box]]\nname = "{name}"\nkind = "{kind}"\ncenter = {v(center)}\nsize = {v(size)}\ncolor = {v(color)}\n'
        if rot:
            s += f"rotation_deg = {v(rot)}\n"
        if hidden:
            s += "hidden = true\n"
        self.out.append(s)
        if kind == "ground":
            self.rects.append((center[0] - size[0] / 2 - 3, center[2] - size[2] / 2 - 3,
                               center[0] + size[0] / 2 + 3, center[2] + size[2] / 2 + 3))

    def pad(self, name, x, z, sx, sz, color=DIRT, y=0.0):
        self.box(name, "ground", [x, y - 0.1, z], [sx, 0.2, sz], color)

    def path(self, name, a, b, w=4.0, color=DIRT):
        """Axis-aligned L path from a to b (x first, then z): 1-2 ground pads."""
        (ax, az), (bx, bz) = a, b
        if abs(bx - ax) > 0.01:
            self.pad(name + "_x", (ax + bx) / 2, az, abs(bx - ax) + w, w, color)
        if abs(bz - az) > 0.01:
            self.pad(name + "_z", bx, (az + bz) / 2, w, abs(bz - az) + w, color)

    def wall(self, name, center, size, color=ROCK, rot=None):
        self.box(name, "wall", center, size, color, rot)

    def poi(self, name, center, radius):
        self.out.append(f'[[poi]]\nname = "{name}"\ncenter = {v(center)}\nradius = {radius}\n')

    def prop(self, name, model, pos, rot=0.0, scale=1.0, poi="", snap=False):
        s = f'[[prop]]\nname = "{name}"\nmodel = "{model}"\nposition = {v(pos)}\nrotation_deg = [0.0, {round(rot, 1)}, 0.0]\nscale = {scale}\n'
        if poi:
            s += f'poi = "{poi}"\n'
        if snap:
            s += "snap = true\n"
        self.out.append(s)

    def free(self, x, z, r=2.0) -> bool:
        return not any(x0 - r < x < x1 + r and z0 - r < z < z1 + r for x0, z0, x1, z1 in self.rects)

    def scatter(self, prefix, models, n, cx, cz, hx, hz, seed, scale=(2.5, 4.0), edge=10.0, avoid=()):
        rnd = random.Random(seed)
        k = tries = 0
        while k < n and tries < n * 40:
            tries += 1
            x, z = cx + rnd.uniform(-hx + edge, hx - edge), cz + rnd.uniform(-hz + edge, hz - edge)
            if not self.free(x, z) or any(math.hypot(x - ax, z - az) < ar for ax, az, ar in avoid):
                continue
            k += 1
            self.prop(f"{prefix}_{k}", rnd.choice(models), [x, 0, z], rnd.uniform(0, 360),
                      round(rnd.uniform(*scale), 2), snap=True)

    def anchor(self, name, pos, yaw=0.0, beat="", snap=False):
        s = f'[[anchor]]\nname = "{name}"\nposition = {v(pos)}\nyaw_deg = {yaw}\n'
        s += f'beat = "{beat}"\n' if beat else ""
        s += "snap = true\n" if snap else ""
        self.out.append(s)

    def waystone(self, point, pos, yaw=0.0):
        self.out.append(f'[[waystone]]\npoint = "{point}"\nposition = {v(pos)}\nyaw_deg = {yaw}\n')

    def chest(self, name, pos, tier="normal", flag="", snap=False, yaw=0.0):
        s = f'[[chest]]\nname = "{name}"\nposition = {v(pos)}\nyaw_deg = {yaw}\ntier = "{tier}"\n'
        s += f'requires_flag = "{flag}"\n' if flag else ""
        s += "snap = true\n" if snap else ""
        self.out.append(s)

    def camp(self, name, center, enemies, respawn=600.0, radius=4.0):
        en = ", ".join(f'{{enemy = "{e}", count = {n}}}' for e, n in enemies)
        self.out.append(f'[[camp]]\nname = "{name}"\ncenter = {v(center)}\nradius = {radius}\n'
                        f'respawn_s = {respawn}\nenemies = [{en}]\n')

    def gate(self, name, center, size, reason="Bob said to stick to the path.", flag="tutorial_done"):
        self.out.append(f'[[gate]]\nname = "{name}"\ncenter = {v(center)}\nsize = {v(size)}\n'
                        f'requires_flag = "{flag}"\nreason = "{reason}"\n')

    def stairs(self, name, x, z, y_top, n, step_xz=(0.0, -1.2), w=3.0, color=DIRT):
        for i in range(n):
            y = y_top * (i + 1) / n
            self.box(f"{name}_{i + 1}", "platform", [x + step_xz[0] * i, y - 0.2, z + step_xz[1] * i],
                     [w, 0.4, w], color)

    def text(self) -> str:
        return BEGIN + "\n".join(self.out) + END


def _val(x) -> str:
    if isinstance(x, list):
        return "[" + ", ".join(f'"{s}"' for s in x) + "]"
    return str(x)


TREES = [N + "tree_oak.glb", N + "tree_fat.glb", N + "tree_detailed.glb", N + "tree_oak_dark.glb"]


def closed() -> Map:
    """A closed level keeps its greybox and dress props. No open-zone terrain."""
    return Map(None)


HALL_STONE = [0.62, 0.58, 0.55]
WOOD = [0.42, 0.3, 0.2]


def association() -> Map:
    """159 W8 Mage Association, 60x90 m, 3 floors, no terrain: the 20x30 grand hall stays as is
    (beats 1-4); the library wing (E, mezzanine at 4 m, archive at 8 m) and the courtyard wing (W)
    open through side doors behind tutorial_done gates."""
    m = Map(None)
    for side, sx in (("east", 1), ("west", -1)):
        cx = 20 * sx
        m.box(f"{side}_wing_floor", "ground", [cx, -0.1, 0], [20, 0.2, 90], [0.5, 0.47, 0.44])
        m.wall(f"{side}_wing_outer", [30.5 * sx, 4, 0], [1, 8, 92], HALL_STONE)
        m.wall(f"{side}_wing_north", [cx, 4, -45.5], [20, 8, 1], HALL_STONE)
        m.wall(f"{side}_wing_south", [cx, 4, 45.5], [20, 8, 1], HALL_STONE)
        m.wall(f"{side}_wing_inner_n", [10.5 * sx, 4, -30.25], [1, 8, 29.5], HALL_STONE)
        m.wall(f"{side}_wing_inner_s", [10.5 * sx, 4, 30.25], [1, 8, 29.5], HALL_STONE)
        m.gate(f"{side}_wing_door", [10.6 * sx, 1.75, 0], [0.5, 3.5, 4.4],
               "The Archmage's wings are closed to novices.", "tutorial_done")
    # Library wing: shelves on the ground floor, a mezzanine (floor 2) and an archive (floor 3).
    for i in range(6):
        m.box(f"shelf_{i + 1}", "wall", [24, 1.6, -40 + i * 6], [8, 3.2, 1], WOOD)
    m.stairs("library_stair", 13, 12, 4.0, 10, (0.0, -1.2), 3.0, WOOD)
    m.box("mezzanine", "platform", [21, 3.8, -21.8], [18, 0.4, 43.6], WOOD)
    for i in range(8):
        m.box(f"archive_stair_{i + 1}", "platform", [28, 4 + 4 * (i + 1) / 8 - 0.2, -4 - 1.2 * i], [3, 0.4, 3], WOOD)
    m.box("archive", "platform", [25, 7.8, -27.5], [9, 0.4, 25], WOOD)
    m.box("archive_rail", "wall", [20.25, 8.6, -27.5], [0.3, 1.2, 25], WOOD)
    m.chest("archive_hidden", [28, 8.0, -38], "hidden")
    m.chest("library_chest", [16, 0, -42], "normal")
    m.anchor("library", [16, 0, 0], 270.0)
    m.poi("library", [20, 0, -10], 25)
    # Courtyard wing: open to the sky, a fountain, planters and trees.
    m.box("fountain", "wall", [-20, 0.5, 0], [6, 1, 6], HALL_STONE)
    m.box("fountain_water", "platform", [-20, 1.02, 0], [5, 0.04, 5], [0.16, 0.28, 0.38])
    for i, (x, z) in enumerate(((-15, -30), (-25, -30), (-15, 30), (-25, 30), (-15, -15), (-25, 15))):
        m.prop(f"courtyard_tree_{i + 1}", TREES[i % len(TREES)], [x, 0, z], 37.0 * i, 3.5, poi="courtyard")
    m.chest("courtyard_chest", [-27, 0, -42], "normal")
    m.anchor("courtyard", [-16, 0, 0], 90.0)
    m.poi("courtyard", [-20, 0, 0], 25)
    return m




MAPS = {
    "data/levels/old_oak.toml": closed,
    "data/levels/town_square.toml": closed,
    "data/levels/mage_association.toml": association,
    "data/levels/midden_greybox.toml": closed,
    "data/levels/breach_slice.toml": closed,
}


def apply(path: Path, block: str) -> str:
    s = path.read_text(encoding="utf-8")
    if BEGIN in s:
        a = s.index(BEGIN)
        b = s.index(END, a) + len(END)
        s = s[:a] + s[b:].removeprefix("\n")  # the "\n" apply() adds before DRESS
    i = s.find(DRESS)
    if i < 0:
        return s.rstrip("\n") + "\n\n" + block
    return s[:i] + block + "\n" + s[i:]


def main(argv: list[str]) -> int:
    stale = 0
    for rel, fn in MAPS.items():
        p = ROOT / rel
        new = apply(p, fn().text())
        if "--check" in argv:
            if new != p.read_text(encoding="utf-8"):
                print(f"[expand_maps] STALE {rel}", file=sys.stderr)
                stale += 1
        elif new != p.read_text(encoding="utf-8"):
            p.write_text(new, encoding="utf-8")
            print(f"[expand_maps] wrote {rel}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
