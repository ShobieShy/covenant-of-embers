import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# ---- EXPAND_BEGIN (generated by tools/expand_maps.py; edit that, not this) ----\n"
END = "# ---- EXPAND_END ----\n"
DRESS = "# ---- DRESS_BEGIN"
N = "assets/kenney/nature-kit/"
