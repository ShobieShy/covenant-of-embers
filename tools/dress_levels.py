def render(text: str, hide: set[str], block: str) -> str:
    text = text.split(BEGIN)[0].rstrip("\n") + "\n"
    text = re.sub(r"\nhidden = true", "", text)
    for name in hide:
        pat = re.compile(r'(\[\[box\]\]\nname = "%s"\n(?:(?!\[\[).*\n)*?color = .*)' % re.escape(name))
        text, n = pat.subn(r"\1\nhidden = true", text, count=1)
        assert n == 1, name
    return text + "\n" + BEGIN + block


def main(argv: list[str]) -> int:
    bad = 0
    for rel, fn in FILES.items():
        path = ROOT / rel
        old = path.read_text(encoding="utf-8")
        new = render(old, *fn())
        if "--check" in argv:
            if new != old:
                print(f"[dress_levels] STALE {rel}", file=sys.stderr)
                bad += 1
        elif new != old:
            path.write_text(new, encoding="utf-8")
            print(f"[dress_levels] wrote {rel}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
