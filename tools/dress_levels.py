"""Town art (Ember Art batch 01): write the kit dressing into the level TOMLs.

Rewrites the block between DRESS_BEGIN and the end of data/levels/{town_square,
mage_association,old_oak}.toml with [[prop]] entries, and marks the greybox boxes the
props replace as `hidden = true` (colliders stay, so gameplay and navigation do not
change). Kenney kit pieces are 1 m tiles; a wall panel sits at local x 0.40..0.50, so a
panel scaled sx along x is offset by 0.45 * sx to centre it in its collider.
  tools/dress_levels.py            rewrite the blocks
  tools/dress_levels.py --check    exit 1 if a TOML is out of date
"""
