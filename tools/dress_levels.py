def prop(name, model, pos, rot=0.0, scale=1.0, count=1, step=(0, 0, 0)):
    sc = f"{scale}" if not isinstance(scale, (list, tuple)) else "[%s]" % ", ".join(f"{round(s, 4)}" for s in scale)
    s = (f'[[prop]]\nname = "{name}"\nmodel = "{model}"\nposition = [{", ".join(str(round(p, 4)) for p in pos)}]\n'
         f"rotation_deg = [0.0, {rot}, 0.0]\nscale = {sc}\n")
    if count > 1:
        s += f"count = {count}\nstep = [{', '.join(str(round(p, 4)) for p in step)}]\n"
    return s


def wall_x(name, piece, x0, x1, zc, h, thick, tile=4.0, y=0.0, flip=False):
    """Panels along X (from x0 to x1) centred on z = zc, `thick` deep, `h` tall."""
    n = max(1, round((x1 - x0) / tile))
    w = (x1 - x0) / n
    sx = thick / 0.1
    off = 0.45 * sx
    rot, dz = (90.0, off) if not flip else (-90.0, -off)
    return prop(name, piece, (x0 + w / 2, y, zc + dz), rot, (sx, h, w), n, (w, 0, 0))


def wall_z(name, piece, z0, z1, xc, h, thick, tile=4.0, y=0.0, flip=False):
    n = max(1, round((z1 - z0) / tile))
    w = (z1 - z0) / n
    sx = thick / 0.1
    off = 0.45 * sx
    rot, dx = (0.0, -off) if not flip else (180.0, off)
    return prop(name, piece, (xc + dx, y, z0 + w / 2), rot, (sx, h, w), n, (0, 0, w))


